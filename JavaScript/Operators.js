//  Arithmetics Operators
let a = 10;
let b = 5;

console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);
console.log(a ** b);


// unary Operators

let c = 10;
let d = 5;
console.log(++c);
console.log(d++);

//  Assignment Operators

let e = 5;
let f = 10;
f = e;
console.log(f);

// Comparison Operators

let age = 18;
console.log(age < 18);
console.log(age > 18);
console.log(age >= 18);
console.log(age <= 18);
console.log(age == 18);
console.log(age != 18);


